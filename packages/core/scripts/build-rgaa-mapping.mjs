/**
 * Generates the RGAA criteria table from the official DINUM source.
 *
 * The reference frame is reference data, not code, and it is versioned on its
 * own schedule — so it is fetched from the authority and transcribed
 * mechanically rather than typed out by hand. Citing a criterion that does not
 * say what we claim is the one mistake this tool cannot afford: the people most
 * likely to pay for it are the auditors best placed to catch it.
 *
 * Run with:  node scripts/build-rgaa-mapping.mjs
 */
import { writeFile } from 'node:fs/promises';
import { createHash } from 'node:crypto';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const SOURCE_URL =
  'https://raw.githubusercontent.com/DISIC/RGAA/master/v4.1/JSON/criteres.json';
const RGAA_VERSION = '4.1.2';
const EXPECTED_CRITERIA = 106;
const EXPECTED_TOPICS = 13;

const OUTPUT = join(
  dirname(fileURLToPath(import.meta.url)),
  '../src/mapping/rgaa-criteria.generated.ts',
);

/** `"9.1.1.1 / 1.1.1 Non-text Content (A)"` -> criterion and level. */
const WCAG_REFERENCE = /^[\d.]+ \/ (\d+\.\d+\.\d+) .+ \((A|AA|AAA)\)$/;

/** Criteria titles are markdown; keep the words, drop the glossary links. */
function toPlainText(markdown) {
  return markdown
    .replace(/\[([^\]]+)\]\([^)]*\)/g, '$1')
    .replace(/`([^`]*)`/g, '$1')
    .replace(/\s+/g, ' ')
    .trim();
}

/** Strictest level wins: a criterion resting on any level-A rule is level A. */
function strictestLevel(levels) {
  for (const candidate of ['A', 'AA', 'AAA']) {
    if (levels.includes(candidate)) return candidate;
  }
  return null;
}

const response = await fetch(SOURCE_URL);
if (!response.ok) throw new Error(`${SOURCE_URL} responded ${response.status}`);

const body = await response.text();
const checksum = createHash('sha256').update(body).digest('hex');
const source = JSON.parse(body);

const criteria = [];
const unparsed = [];

for (const topic of source.topics) {
  for (const entry of topic.criteria) {
    const criterion = entry.criterium;
    const wcag = [];
    const levels = [];

    for (const reference of criterion.references ?? []) {
      for (const raw of reference.wcag ?? []) {
        const match = WCAG_REFERENCE.exec(raw);
        if (!match) {
          unparsed.push(raw);
          continue;
        }
        if (!wcag.includes(match[1])) wcag.push(match[1]);
        levels.push(match[2]);
      }
    }

    criteria.push({
      id: `${topic.number}.${criterion.number}`,
      topic: topic.number,
      topicName: topic.topic,
      title: toPlainText(criterion.title),
      wcag,
      level: strictestLevel(levels),
      testCount: Object.keys(criterion.tests ?? {}).length,
    });
  }
}

// Fail loudly rather than silently shipping a partial reference frame: a table
// that is quietly missing criteria is worse than no table at all.
if (unparsed.length > 0) {
  throw new Error(`unrecognised WCAG reference(s):\n${[...new Set(unparsed)].join('\n')}`);
}
if (criteria.length !== EXPECTED_CRITERIA) {
  throw new Error(`expected ${EXPECTED_CRITERIA} criteria, parsed ${criteria.length}`);
}
const topics = new Set(criteria.map((criterion) => criterion.topic));
if (topics.size !== EXPECTED_TOPICS) {
  throw new Error(`expected ${EXPECTED_TOPICS} topics, found ${topics.size}`);
}

const file = `// Generated by scripts/build-rgaa-mapping.mjs — do not edit by hand.
//
// Source: ${SOURCE_URL}
// SHA-256: ${checksum}
// RGAA ${RGAA_VERSION} · ${criteria.length} criteria across ${topics.size} topics
//
// Regenerate when the reference frame is updated, then review the diff: a change
// here changes what every audit cites.

import type { WcagLevel } from './wcag.js';

export interface RgaaCriterion {
  /** Dotted identifier, e.g. "1.1". */
  id: string;
  /** Topic number, 1 to 13. */
  topic: number;
  topicName: string;
  title: string;
  /** WCAG success criteria this RGAA criterion rests on. */
  wcag: readonly string[];
  /** Strictest level among those criteria; null when it references none. */
  level: WcagLevel | null;
  /** Number of tests the official method defines for this criterion. */
  testCount: number;
}

export const RGAA_SOURCE_CHECKSUM = '${checksum}';

export const RGAA_CRITERIA: readonly RgaaCriterion[] = ${JSON.stringify(criteria, null, 2)};
`;

await writeFile(OUTPUT, file, 'utf8');

const mapped = criteria.filter((criterion) => criterion.wcag.length > 0).length;
console.log(`wrote ${OUTPUT}`);
console.log(`${criteria.length} criteria, ${mapped} carrying WCAG references`);
console.log(`checksum ${checksum}`);
